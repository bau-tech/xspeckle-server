import type { DataStruct, LegacyData } from '@/modules/comments/services/data'
import type { SmartTextEditorValueSchema } from '@/modules/core/services/richTextEditorService'
import type { Nullable } from '@/modules/shared/helpers/typeHelper'

export type CommentLinkResourceType = 'stream' | 'commit' | 'object' | 'comment'

export interface CommentRecord {
  id: string
  streamId: string
  authorId: string
  createdAt: Date
  updatedAt: Date
  text: Nullable<string | SmartTextEditorValueSchema>
  screenshot: Nullable<string>
  data: Nullable<LegacyData | DataStruct>
  parentComment: Nullable<string>
  /**
   * BCF Topic fields. Only meaningful when parentComment is null (a Topic
   * row) -- always null/empty on a Comment row (a reply), enforced at the
   * service layer, not a DB constraint.
   */
  title: Nullable<string>
  topicType: Nullable<string>
  topicStatus: Nullable<string>
  priority: Nullable<string>
  stage: Nullable<string>
  labels: Nullable<string[]>
  dueDate: Nullable<Date>
  assignedTo: Nullable<string>
  /**
   * BCF 3.0's per-project sequential topic number (server_assigned_id is
   * derived from this, not stored separately). Only set on Topic rows.
   */
  index: Nullable<number>
  /**
   * BCF guid, shared with the external BCF server -- the identity the two are
   * synced on. Set on every row (Topic and Comment).
   */
  guid: string
  /**
   * BCF's string identity (an email) of whoever created/last modified the
   * row. Separate from authorId: a row synced in from another BCF server
   * keeps its original author even though a sync user wrote it here.
   */
  creationAuthor: Nullable<string>
  modifiedAuthor: Nullable<string>
  modifiedDate: Nullable<Date>
  /** Topic rows only. */
  referenceLinks: Nullable<string[]>
  /** Topic rows only. */
  bimSnippet: Nullable<BcfBimSnippet>
  /** Comment rows only: the topic viewpoint (topic_viewpoints.guid) it refers to. */
  viewpointGuid: Nullable<string>
}

/** BCF 3.0 bim_snippet, in the spec's own wire shape. */
export interface BcfBimSnippet {
  snippet_type: string
  is_external: boolean
  reference: string
  reference_schema: string
}

export interface CommentLinkRecord {
  commentId: string
  resourceId: string
  resourceType: CommentLinkResourceType
}

export interface CommentViewRecord {
  commentId: string
  userId: string
  viewedAt: Date
}

export interface CommentRelatedTopicRecord {
  topicId: string
  relatedTopicId: string
}

export interface CommentDocumentReferenceRecord {
  id: string
  topicId: string
  documentGuid: Nullable<string>
  url: Nullable<string>
  description: Nullable<string>
  /** BCF guid; generated by the DB when omitted. */
  guid?: string
}

type BcfVector3 = { x: number; y: number; z: number }

export interface BcfComponent {
  ifc_guid?: Nullable<string>
  originating_system?: Nullable<string>
  authoring_tool_id?: Nullable<string>
}

export interface BcfCamera {
  camera_view_point: BcfVector3
  camera_direction: BcfVector3
  camera_up_vector: BcfVector3
  field_of_view?: number
  view_to_world_scale?: number
  aspect_ratio?: Nullable<number>
}

/**
 * A BCF 3.0 viewpoint minus its snapshot/bitmap bytes, in the spec's own
 * snake_case wire shape (the same shape the external BCF server serves), so
 * it round-trips losslessly.
 */
export interface BcfViewpointData {
  perspective_camera?: Nullable<BcfCamera>
  orthogonal_camera?: Nullable<BcfCamera>
  lines: Array<{ start_point: BcfVector3; end_point: BcfVector3 }>
  clipping_planes: Array<{ location: BcfVector3; direction: BcfVector3 }>
  components: {
    selection: BcfComponent[]
    coloring: Array<{ color: string; components: BcfComponent[] }>
    visibility: {
      default_visibility: boolean
      exceptions: BcfComponent[]
      view_setup_hints?: Nullable<{
        spaces_visible?: Nullable<boolean>
        space_boundaries_visible?: Nullable<boolean>
        openings_visible?: Nullable<boolean>
      }>
    }
  }
}

/**
 * A BCF viewpoint of a topic -- the only place viewpoints live (a topic's
 * creation-time view and a comment's view are rows here too; a comment
 * points at one via its viewpointGuid). `bcf` is authoritative for the BCF
 * fields; `data` is the Speckle viewer state used to restore the exact 3D
 * view. Either can be derived from the other, and old rows only have `data`.
 */
export interface TopicViewpointRecord {
  id: string
  topicId: string
  authorId: Nullable<string>
  data: Nullable<DataStruct>
  screenshot: Nullable<string>
  createdAt: Date
  guid: string
  index: Nullable<number>
  bcf: Nullable<BcfViewpointData>
  /** 'png' | 'jpg' */
  snapshotType: Nullable<string>
}
